const fs = require('fs');
const path = require('path');

const vehicleRegistryArtifact = require('../artifacts/contracts/VehicleRegistry.sol/VehicleRegistry.json');
const carChainEscrowArtifact = require('../artifacts/contracts/CarChainEscrow.sol/CarChainEscrow.json');

const targetDir = path.join(__dirname, '..', '..', 'frontend', 'contracts');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const abisContent = `// Auto-generated by blockchain/scripts/export-frontend.js
window.CarChainABIs = {
  VehicleRegistry: ${JSON.stringify(vehicleRegistryArtifact.abi, null, 2)},
  CarChainEscrow: ${JSON.stringify(carChainEscrowArtifact.abi, null, 2)}
};
`;

fs.writeFileSync(path.join(targetDir, 'abis.js'), abisContent);
console.log('Successfully generated frontend/contracts/abis.js');
