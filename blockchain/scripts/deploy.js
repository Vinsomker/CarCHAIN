const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await ethers.getSigners();
  const network = await ethers.provider.getNetwork();

  console.log("==================================================");
  console.log("Deploying CarChain Smart Contracts");
  console.log("Deployer Address:", deployer.address);
  console.log("Deployer Balance:", ethers.formatEther(await ethers.provider.getBalance(deployer.address)), "ETH");
  console.log("Network:", network.name, "(chainId:", network.chainId.toString(), ")");
  console.log("==================================================");

  // 1. Deploy VehicleRegistry
  console.log("\n1. Deploying VehicleRegistry...");
  const VehicleRegistryFactory = await ethers.getContractFactory("VehicleRegistry");
  const vehicleRegistry = await VehicleRegistryFactory.deploy(deployer.address);
  await vehicleRegistry.waitForDeployment();
  const vehicleRegistryAddress = await vehicleRegistry.getAddress();
  console.log("VehicleRegistry deployed to:", vehicleRegistryAddress);

  // 2. Deploy CarChainEscrow
  console.log("\n2. Deploying CarChainEscrow...");
  const CarChainEscrowFactory = await ethers.getContractFactory("CarChainEscrow");
  const escrow = await CarChainEscrowFactory.deploy(vehicleRegistryAddress, deployer.address);
  await escrow.waitForDeployment();
  const escrowAddress = await escrow.getAddress();
  console.log("CarChainEscrow deployed to:", escrowAddress);

  // 3. Export deployment artifacts for Frontend and Backend
  const deploymentData = {
    network: network.name,
    chainId: Number(network.chainId),
    deployedAt: new Date().toISOString(),
    deployer: deployer.address,
    contracts: {
      VehicleRegistry: {
        address: vehicleRegistryAddress,
      },
      CarChainEscrow: {
        address: escrowAddress,
      },
    },
  };

  const deploymentPath = path.join(__dirname, "..", "deployments.json");
  fs.writeFileSync(deploymentPath, JSON.stringify(deploymentData, null, 2));
  console.log("\nSaved deployment details to:", deploymentPath);

  // Also write to frontend/contracts/deployedAddresses.js for direct web3 inclusion
  const frontendContractsDir = path.join(__dirname, "..", "..", "frontend", "contracts");
  if (!fs.existsSync(frontendContractsDir)) {
    fs.mkdirSync(frontendContractsDir, { recursive: true });
  }

  const jsConfig = `// Auto-generated by blockchain/scripts/deploy.js
window.CarChainContracts = {
  network: "${network.name}",
  chainId: ${network.chainId.toString()},
  VehicleRegistry: "${vehicleRegistryAddress}",
  CarChainEscrow: "${escrowAddress}",
  deployedAt: "${new Date().toISOString()}"
};
`;

  fs.writeFileSync(path.join(frontendContractsDir, "deployedAddresses.js"), jsConfig);
  console.log("Saved frontend contract config to:", path.join(frontendContractsDir, "deployedAddresses.js"));
  console.log("==================================================");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });
